def get_doc(doc_id: str) -> dict:
    """公开读取：有自定义返回自定义，否则回退内置默认（customized 标记来源）。"""
    key = DOCS[doc_id]
    row = repo.get_doc(key)
    if row is None:
        return {
            "id": doc_id,
            "content": DEFAULT_PRIVACY_POLICY,
            "updatedBy": None,
            "updatedAt": None,
            "customized": False,
        }
    return {
        "id": doc_id,
        "content": row["content"],
        "updatedBy": row["updated_by"],
        "updatedAt": row["updated_at"],
        "customized": True,
    }


def save_doc(doc_id: str, content: str, uid: str) -> None:
    if doc_id not in DOCS:
        raise ValueError(f"未知文档：{doc_id}")
    repo.upsert_doc(DOCS[doc_id], content, uid)
